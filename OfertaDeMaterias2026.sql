/*CONSULTA 1: MOSTRAR LOS GRUPOS Y LOS DOCENTES QUE ESTAN ENSEÑANDO LA MATERIA
DE BASES DE DATOS I EN EL SEMESTRE 1-2026*/
SELECT G.NOMBRE AS GRUPO , D.NOMBRE AS DOCENTE
FROM GRUPO G, DOCENTE D, MATERIA M, SEMESTRE S
WHERE D.CODIGO = G.CODIGODOC AND M.SIGLA = G.SIGLAMAT AND S.ID = G.IDSEMESTRE AND M.NOMBRE = 'BASE DE DATOS I';

/*CONSULTA 2: MOSTRAR LAS MATERIAS Y EL GRUPO DE QUE TIENEN EL HORARIO
LOS DIAS LUNES DE 7:00 A 8:30 EN EL SEMESTRE 1-2026*/
SELECT G.NOMBRE AS GRUPO , M.NOMBRE AS MATERIA
FROM GRUPO G , MATERIA M , HORARIO H , SEMESTRE S
WHERE G.ID = H.IDGRUPO AND S.ID = G.IDSEMESTRE AND M.SIGLA = G.SIGLAMAT AND H.DIA = 'LUNES';

/*ONSULTA 3: MOSTRAR LOS ALUMNOS QUE HAN INSCRITO MATERIAS EN EL SEMESTRE 1-2026
LOS DIAS MARTES Y JUEVES DE 7:00 A 9:15*/
SELECT G.ID , E.NOMBRE , H.DIA ,S.ID
FROM ESTUDIANTE E , BOLETAINSC BI , SEMESTRE S , INSCRIBE I , HORARIO H , GRUPO G
WHERE E.REGISTRO = BI.REGISTROEST AND S.ID = BI.IDSEMESTRE AND BI.NRO = I.NROBO AND G.ID = I.IDGRUPO
		AND G.ID = H.IDGRUPO AND (H.DIA = 'MARTES' OR H.DIA = 'JUEVES') AND H.HORAI >= '07:00:00'
        AND H.HORAF <= '09:15:00';

/*CONSULTA 4: MOSTRAR POR CADA ALUMNO CUANTAS BOLETAS DE INSCRIPCION TIENE EN EL
SEMESTRE 1-2026*/
