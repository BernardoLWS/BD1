/*TABLA BOLETA DE INSCRIPCION*/
CREATE TABLE BOLETAINSC
(
	NRO SMALLINT NOT NULL PRIMARY KEY,
    FECHA DATE NOT NULL,
    HORA TIME NOT NULL,
    REGISTROEST INT NOT NULL,
    FOREIGN KEY (REGISTROEST) REFERENCES ESTUDIANTE(REGISTRO)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
	IDSEMESTRE SMALLINT NOT NULL,
    FOREIGN KEY (IDSEMESTRE) REFERENCES SEMESTRE(ID)
		ON UPDATE CASCADE
        ON DELETE CASCADE
);

 /* TABLA GRUPO*/
 CREATE TABLE GRUPO
 (
   ID SMALLINT NOT NULL PRIMARY KEY,
   NOMBRE VARCHAR(2) NOT NULL,
   CUPO SMALLINT NOT NULL,
   SIGLAMAT VARCHAR(6),
   FOREIGN KEY (SIGLAMAT) REFERENCES MATERIA(SIGLA)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
   CODIGODOC SMALLINT,
   FOREIGN KEY (CODIGODOC) REFERENCES DOCENTE(CODIGO)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
   IDSEMESTRE SMALLINT NOT NULL,
   FOREIGN KEY (IDSEMESTRE) REFERENCES SEMESTRE(ID)
		ON UPDATE CASCADE
        ON DELETE CASCADE
);
/*TABLA HORARIO*/
CREATE TABLE HORARIO
( 
  IDGRUPO SMALLINT NOT NULL,
  FOREIGN KEY (IDGRUPO) REFERENCES GRUPO(ID)
		ON UPDATE CASCADE
        ON DELETE CASCADE,
  IDHO TINYINT NOT NULL,
  PRIMARY KEY (IDGRUPO, IDHO),
  DIA VARCHAR(9) NOT NULL,
  HORAI TIME NOT NULL,
  HORAF TIME NOT NULL
);
/*TABLA INSCRIBE*/
CREATE TABLE INSCRIBE
(
   NROBO SMALLINT NOT NULL,
   IDGRUPO SMALLINT NOT NULL,
   PRIMARY KEY(NROBO,IDGRUPO),
   FOREIGN KEY (NROBO) REFERENCES BOLETAINSC(NRO)
	  ON UPDATE CASCADE
      ON DELETE CASCADE,
   FOREIGN KEY (IDGRUPO) REFERENCES GRUPO(ID)
	  ON UPDATE CASCADE
